def read_rgb(path):
    img = Image.open(path).convert("RGB")
    return np.asarray(img).astype(np.float32) / 255.0

def rgb_to_luma(img):
    return 0.2126*img[...,0] + 0.7152*img[...,1] + 0.0722*img[...,2]

def random_flip_rot(low, high):
    if random.random() < 0.5:
        low = low[:, ::-1, :].copy()
        high = high[:, ::-1, :].copy()
    if random.random() < 0.2:
        low = low[::-1, :, :].copy()
        high = high[::-1, :, :].copy()
    if random.random() < 0.3:
        k = random.randint(1, 3)
        low = np.rot90(low, k, axes=(0, 1)).copy()
        high = np.rot90(high, k, axes=(0, 1)).copy()
    return low, high

def dark_biased_crop(low, high, crop_size=384, tries=5):
    H, W, _ = low.shape
    if H < crop_size or W < crop_size:
        pad_h = max(0, crop_size - H)
        pad_w = max(0, crop_size - W)
        low  = cv2.copyMakeBorder(low, 0, pad_h, 0, pad_w, cv2.BORDER_REFLECT_101)
        high = cv2.copyMakeBorder(high, 0, pad_h, 0, pad_w, cv2.BORDER_REFLECT_101)
        H, W, _ = low.shape

    best = None
    for _ in range(tries):
        y = random.randint(0, H - crop_size)
        x = random.randint(0, W - crop_size)
        patch = low[y:y+crop_size, x:x+crop_size, :]
        lum = float(rgb_to_luma(patch).mean())
        if best is None or lum < best[0]:
            best = (lum, x, y)

    _, x, y = best
    return low[y:y+crop_size, x:x+crop_size, :], high[y:y+crop_size, x:x+crop_size, :]

def poisson_gaussian_noise(img, shot_range=(0.0005, 0.01), read_range=(0.0, 0.002)):
    x = np.clip(img, 0, 1)
    shot = random.uniform(*shot_range)
    read = random.uniform(*read_range)
    shot_var = shot * x
    noise_shot = np.random.normal(0, 1, x.shape).astype(np.float32) * np.sqrt(shot_var + 1e-8)
    noise_read = np.random.normal(0, 1, x.shape).astype(np.float32) * read
    return np.clip(x + noise_shot + noise_read, 0, 1)

def jpeg_recompress(img, qmin=80, qmax=95):
    q = random.randint(qmin, qmax)
    x = (np.clip(img, 0, 1) * 255.0).round().astype(np.uint8)
    bgr = cv2.cvtColor(x, cv2.COLOR_RGB2BGR)
    ok, enc = cv2.imencode(".jpg", bgr, [int(cv2.IMWRITE_JPEG_QUALITY), q])
    if not ok:
        return img
    dec = cv2.imdecode(enc, cv2.IMREAD_COLOR)
    rgb = cv2.cvtColor(dec, cv2.COLOR_BGR2RGB).astype(np.float32) / 255.0
    return np.clip(rgb, 0, 1)

class LOLPairsDataset(Dataset):
    def __init__(self, pairs, low_dir, high_dir, crop_size=384, training=False):
        self.pairs = pairs
        self.low_dir = low_dir
        self.high_dir = high_dir
        self.crop_size = crop_size
        self.training = training

    def __len__(self):
        return len(self.pairs)

    def __getitem__(self, idx):
        low_file, high_file = self.pairs[idx]

        low  = read_rgb(os.path.join(self.low_dir, low_file))
        high = read_rgb(os.path.join(self.high_dir, high_file))

        if self.training:
            low, high = random_flip_rot(low, high)
            low, high = dark_biased_crop(low, high, crop_size=self.crop_size)

            if random.random() < 0.4:
                low = poisson_gaussian_noise(low)

            if random.random() < 0.15:
                low = jpeg_recompress(low)

        low_t  = torch.from_numpy(low.transpose(2,0,1)).float()
        high_t = torch.from_numpy(high.transpose(2,0,1)).float()
        return low_t, high_t

