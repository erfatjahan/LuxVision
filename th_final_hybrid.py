class HybridLoss(nn.Module):
    def __init__(self, ssim_weight=0.2):
        super(HybridLoss, self).__init__()
        self.ssim_weight = ssim_weight

    def forward(self, pred, target):

        char_loss = torch.mean(torch.sqrt((pred - target)**2 + 1e-6))


        ssim_loss = 1 - structural_similarity_index_measure(pred, target, data_range=1.0)

        return char_loss + (self.ssim_weight * ssim_loss)
def train_one_epoch(model, loader, optimizer):
    model.train()
    total_loss = 0
    criterion = HybridLoss().to(device)

    for low, high in tqdm(loader, desc="Training"):
        low, high = low.to(device), high.to(device)

        optimizer.zero_grad()
        output = model(low)
        loss = criterion(output, high)

        loss.backward()
        optimizer.step()

        total_loss += loss.item()
    return total_loss / len(loader)

def validate(model, loader):
    model.eval()
    t_loss, t_psnr, t_ssim = 0, 0, 0
    criterion = HybridLoss().to(device)

    with torch.no_grad():
        for low, high in tqdm(loader, desc="Validating", leave=False):
            low, high = low.to(device), high.to(device)

            pred = model(low).clamp(0, 1)

            t_loss += criterion(pred, high).item()
            t_psnr += peak_signal_noise_ratio(pred, high, data_range=1.0).item()
            t_ssim += structural_similarity_index_measure(pred, high, data_range=1.0).item()

    return t_loss/len(loader), t_psnr/len(loader), t_ssim/len(loader)

